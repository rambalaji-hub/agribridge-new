/**
 * Localizes any crop name dynamically
 */
export function localizeCrop(cropName: string, lang: LanguageCode): string {
  if (!cropName) return '';
  const match = CROP_TRANSLATIONS[cropName];
  if (match && match[lang]) {
    return match[lang];
  }
  // If partial match like 'Paddy' or 'Wheat'
  for (const key of Object.keys(CROP_TRANSLATIONS)) {
    if (cropName.toLowerCase().includes(key.toLowerCase()) || key.toLowerCase().includes(cropName.toLowerCase())) {
      return CROP_TRANSLATIONS[key][lang] || cropName;
    }
  }
  return cropName;
}

/**
 * Localizes centre/mandi name
 */
export function localizeMandi(centreName: string, lang: LanguageCode): string {
  if (!centreName) return '';
  const match = CENTRE_TRANSLATIONS[centreName];
  if (match && match[lang]) {
    return match[lang];
  }
  return centreName;
}

/**
 * Retrieves a UI string by key with multi-lingual fallback
 */
export function tFull(key: string, lang: LanguageCode, fallback?: string): string {
  const item = UI_TRANSLATIONS[key];
  if (item && item[lang]) {
    return item[lang];
  }
  return fallback || item?.['en'] || key;
}
